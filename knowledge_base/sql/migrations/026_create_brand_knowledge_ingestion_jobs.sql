CREATE TABLE IF NOT EXISTS brand_knowledge_ingestion_jobs (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    job_id VARCHAR(128) NOT NULL COMMENT '入库任务ID',
    brand_code VARCHAR(64) NOT NULL COMMENT '品牌业务编码',
    brand_name VARCHAR(255) NOT NULL COMMENT '品牌名称',
    full_knowledge_file_id BIGINT NULL COMMENT '对应知识库文件ID',
    document_id VARCHAR(128) NULL COMMENT 'Milvus文档ID',
    version_no INT NOT NULL COMMENT '版本号Vx中的x',
    knowledge_date CHAR(8) NOT NULL COMMENT '知识库版本日期YYYYMMDD',
    revision_no INT NOT NULL DEFAULT 1 COMMENT '同版本修订号',
    original_filename VARCHAR(1024) NOT NULL COMMENT '原始上传文件名',
    source_ext VARCHAR(32) NULL COMMENT '原始文件扩展名',
    content_hash CHAR(64) NULL COMMENT '最终Markdown内容SHA256',
    force_reingest TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否强制重建',
    status VARCHAR(32) NOT NULL COMMENT '任务状态：waiting/processing/success/failed/skipped',
    current_step VARCHAR(64) NULL COMMENT '当前执行步骤',
    parse_status VARCHAR(32) NULL COMMENT '解析状态',
    pdf_status VARCHAR(32) NULL COMMENT 'PDF生成状态',
    mysql_status VARCHAR(32) NULL COMMENT 'MySQL写入状态',
    milvus_status VARCHAR(32) NULL COMMENT 'Milvus写入状态',
    facts_status VARCHAR(32) NULL COMMENT '事实提取状态',
    cleanup_status VARCHAR(32) NULL COMMENT '旧数据清理状态',
    retry_count INT NOT NULL DEFAULT 0 COMMENT '重试次数',
    error_message TEXT NULL COMMENT '失败原因',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_brand_knowledge_ingestion_job (job_id),
    INDEX idx_brand_knowledge_jobs_brand (brand_code, created_at),
    INDEX idx_brand_knowledge_jobs_status (status, updated_at),
    INDEX idx_brand_knowledge_jobs_document (document_id)
) COMMENT='品牌AI知识库正式入库任务表';

CREATE TABLE IF NOT EXISTS brand_knowledge_sessions (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    session_id VARCHAR(64) NOT NULL COMMENT '会话ID',
    brand_id BIGINT NULL COMMENT '品牌ID',
    brand_name VARCHAR(255) NULL COMMENT '品牌名称，聊天式首轮可后解析补全',
    status VARCHAR(32) NOT NULL COMMENT '会话状态：running/waiting_user_input/completed/failed/cancelled',
    current_round INT NOT NULL DEFAULT 0 COMMENT '当前轮次',
    initial_user_message TEXT NULL COMMENT '用户首轮输入',
    latest_user_message TEXT NULL COMMENT '最近一次用户输入',
    latest_assistant_message LONGTEXT NULL COMMENT '最近一次助手回复',
    source_documents_json JSON NULL COMMENT '源文档信息',
    latest_draft_markdown LONGTEXT NULL COMMENT '当前最新草稿',
    latest_conflicts_json JSON NULL COMMENT '当前轮待处理冲突',
    latest_conflict_markdown LONGTEXT NULL COMMENT '当前轮冲突说明markdown',
    resolution_history_json JSON NULL COMMENT '历史决策记录',
    final_markdown LONGTEXT NULL COMMENT '最终品牌知识库markdown',
    final_oss_key VARCHAR(512) NULL COMMENT '最终知识库OSS key',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_brand_knowledge_session_id (session_id),
    INDEX idx_brand_knowledge_brand_status (brand_name, status),
    INDEX idx_brand_knowledge_brand_round (brand_name, current_round),
    INDEX idx_brand_knowledge_status (status, updated_at)
) COMMENT='品牌知识库多轮会话表';

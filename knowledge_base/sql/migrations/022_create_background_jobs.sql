CREATE TABLE IF NOT EXISTS background_jobs (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    job_id VARCHAR(128) NOT NULL COMMENT '任务ID',
    job_type VARCHAR(96) NOT NULL COMMENT '任务类型',
    source_type VARCHAR(64) NULL COMMENT '业务来源类型',
    source_id VARCHAR(128) NULL COMMENT '业务来源ID，用于幂等',
    status VARCHAR(32) NOT NULL COMMENT '任务状态：waiting/processing/retrying/success/failed/canceled',
    priority INT NOT NULL DEFAULT 100 COMMENT '优先级，数字越小越优先',
    payload_json JSON NULL COMMENT '任务输入参数JSON',
    result_json JSON NULL COMMENT '任务执行结果JSON',
    retry_count INT NOT NULL DEFAULT 0 COMMENT '已重试次数',
    max_retries INT NOT NULL DEFAULT 3 COMMENT '最大重试次数',
    next_retry_at TIMESTAMP NULL DEFAULT NULL COMMENT '下次重试时间',
    locked_by VARCHAR(128) NULL COMMENT '锁定该任务的 worker 标识',
    locked_at TIMESTAMP NULL DEFAULT NULL COMMENT '锁定时间',
    last_error_message TEXT NULL COMMENT '最近一次错误信息',
    started_at TIMESTAMP NULL DEFAULT NULL COMMENT '最近一次开始处理时间',
    finished_at TIMESTAMP NULL DEFAULT NULL COMMENT '任务完成时间',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_background_jobs_job_id (job_id),
    UNIQUE KEY uk_background_jobs_source (job_type, source_id),
    INDEX idx_background_jobs_status (status, next_retry_at, priority, created_at),
    INDEX idx_background_jobs_type_status (job_type, status),
    INDEX idx_background_jobs_locked (locked_by, locked_at)
) COMMENT='通用后台异步任务表';
